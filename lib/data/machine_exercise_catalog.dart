/// Reviewed product identities, not an assertion that a gym owns each machine.
/// Brand/model IDs intentionally do not merge with generic exercise histories.
class MachineExercise {
  const MachineExercise(
    this.id,
    this.brand,
    this.line,
    this.model,
    this.name,
    this.englishName,
    this.muscle,
    this.focus,
    this.sourceUrl,
  );
  final String id,
      brand,
      line,
      model,
      name,
      englishName,
      muscle,
      focus,
      sourceUrl;

  ExerciseTemplate get exercise => ExerciseTemplate(
    id: 'machine_$id',
    name: '$brand $line $name',
    nameEnglish: englishName,
    muscle: muscle,
    icon: SetflowIcons.equipment,
    equipmentKey: 'machine',
    aliases: [
      model,
      focus,
      line,
      if (brand == '테크노짐') 'Technogym',
      if (brand == '파나타') ...['Panatta', '파나따'],
      if (brand == '뉴텍') ...[
        'Newtech',
        if (line == '어드벤스') ...['Advance', '어드밴스'],
      ],
      if (brand == '해머스트렝스') ...['Hammer Strength', '해머스트랭스', '해머스랭스'],
    ],
    sourceName: 'manufacturer-catalog',
    sourceId: id,
    primaryMuscles: switch (focus) {
      '대퇴사두근' => const ['quadriceps'],
      '햄스트링' => const ['hamstrings'],
      '둔근' => const ['glutes'],
      '내전근' => const ['adductors'],
      '고관절 외전근' => const ['abductors'],
      '종아리' => const ['calves'],
      '이두근' => const ['biceps'],
      '삼두근' => const ['triceps'],
      '전완' => const ['forearms'],
      '승모근' => const ['traps'],
      _ => switch (muscle) {
        '가슴' => const ['chest'],
        '등' => const ['lats'],
        '어깨' => const ['shoulders'],
        '복근' => const ['abdominals'],
        // Compound legs / unusual targets remain text rather than a false map.
        _ => const [],
      },
    },
  );
}

